// Test data is created through the same RPC API the app uses (POST /api/v1/<resource>/<action>,
// body only), via the Vite proxy of the test stack. Names carry a per-run unique prefix.
import type { APIRequestContext } from '@playwright/test';
import type { CabinetDetailDto, DataCenterDto, RoomDto } from '@contracts/hierarchy';
import type { DeviceDetailDto } from '@contracts/devices';
import type { PanelDetailDto } from '@contracts/panels';
import type { CableDto } from '@contracts/cables';
import type { LabelResolveResult } from '@contracts/labels';
import type { WorkstationDto } from '@contracts/workstations';

export async function rpc<T>(request: APIRequestContext, path: string, body: unknown): Promise<T> {
  const res = await request.post(`/api/v1/${path}`, { data: body });
  if (!res.ok()) throw new Error(`${path} failed: ${res.status()} ${await res.text()}`);
  return (await res.json()) as T;
}

let seq = 0;
/** Unique, readable names: E2E-<tag>-<run>-<n>. */
export const uniq = (tag: string) => `E2E-${tag}-${Date.now().toString(36)}-${++seq}`;

/** A label number nobody uses yet: generated by the server, never bound. */
export async function nextLabel(request: APIRequestContext): Promise<number> {
  const r = await rpc<{ created: number[] }>(request, 'labels/generate', { count: 1 });
  return r.created[0];
}
export const display = (n: number) => `E-${String(n).padStart(5, '0')}`;

export interface Hierarchy {
  dc: DataCenterDto;
  room: RoomDto;
  cabinet: CabinetDetailDto;
  device: DeviceDetailDto;
  panel: PanelDetailDto;
}

/** DC > room > cabinet > device (U1) > panel with `ports` RJ45 ports numbered 1..n. */
export async function createHierarchy(request: APIRequestContext, opts: { ports?: number; room?: { widthM: number; depthM: number } } = {}): Promise<Hierarchy> {
  const dc = await rpc<DataCenterDto>(request, 'datacenters/create', { name: uniq('dc') });
  const room = await rpc<RoomDto>(request, 'rooms/create', { dataCenterId: dc.id, name: uniq('room'), ...(opts.room ?? {}) });
  const cabinet = await rpc<CabinetDetailDto>(request, 'cabinets/create', { roomId: room.id, name: uniq('cab'), heightU: 42 });
  const device = await rpc<DeviceDetailDto>(request, 'devices/create', { name: uniq('sw'), type: 'SWITCH', cabinetId: cabinet.id, uPosition: 1, uHeight: 1 });
  let panel = await rpc<PanelDetailDto>(request, 'panels/create', { deviceId: device.id, name: uniq('panel'), type: 'NETWORK', labelShortId: await nextLabel(request) });
  if (opts.ports) {
    await rpc(request, 'ports/create-bulk', { panelId: panel.id, count: opts.ports, prefix: '', startNumber: 1, portType: 'RJ45' });
    panel = await rpc<PanelDetailDto>(request, 'panels/get', { id: panel.id });
  }
  return { dc, room, cabinet, device, panel };
}

export const resolveLabel = (request: APIRequestContext, shortId: number) => rpc<LabelResolveResult>(request, 'labels/resolve', { shortId });
export const getCable = (request: APIRequestContext, id: string) => rpc<CableDto>(request, 'cables/get', { id });
export const getPanel = (request: APIRequestContext, id: string) => rpc<PanelDetailDto>(request, 'panels/get', { id });

export async function createWorkstation(request: APIRequestContext, roomId: string, name: string, fp: { fpX: number; fpY: number }) {
  return rpc<WorkstationDto>(request, 'workstations/create', { roomId, name, fpW: 0.7, fpD: 0.6, ...fp });
}
